#!/usr/bin/env python3
"""
sec_output.py — 输出安全防护模块

检查 AI 输出内容的安全性，拦截敏感/违规内容。

用法:
  python3 sec_output.py --text "<输出文本>"     # 检查单段输出
  python3 sec_output.py --file <路径>            # 从文件读取
  python3 sec_output.py --batch <路径>           # 批量检查（逐行）
"""

import sys
import re
import json

# ── 敏感内容特征 ──────────────────────────────────────────────────────

SENSITIVE_PATTERNS = {
    "高危违法": [
        r"(?i)如何.{0,20}(制作|制造|合成|配制).{0,10}(炸弹|炸药|毒品|毒药|冰毒|海洛因|病毒|武器|枪支|弹药)",
        r"(?i)(make|create|synthesize|produce).{0,20}(bomb|explosive|drug|heroin|cocaine|weapon|gun|poison|virus)",
        r"(?i)如何.{0,20}(自杀|自残|伤害.{0,5}自己)",
        r"(?i)(suicide|self-harm|self-harm|kill yourself)",
        r"(?i)儿童.{0,10}(色情|淫秽|裸露|性)",
        r"(?i)child.{0,10}(porn|abuse|exploitation|sexual)",
    ],
    "个人信息泄露": [
        r"(?i)(身份证|护照|驾驶证|银行卡|信用卡)\s*[：:]\s*[\dXx]{15,18}",
        r"(?i)(手机|电话|手机号|tel|phone)\s*[：:]\s*1[3-9]\d{9}",
        r"(?i)(邮箱|email|e-mail)\s*[：:]\s*\S+@\S+\.\S+",
        r"(?i)(住址|地址|address)\s*[：:].{10,100}",
    ],
    "系统安全": [
        r"(?i)(api[_-]?key|api[_-]?secret|access[_-]?token|secret[_-]?key|private[_-]?key)",
        r"(?i)(password|passwd|pwd|login|credentials)\s*[=:].{4,}",
        r"(?i)(sk-[a-zA-Z0-9]{20,}|pk-[a-zA-Z0-9]{20,})",
        r"(?i)-----BEGIN\s+(RSA|OPENSSH|PGP|EC)\s+PRIVATE\s+KEY-----",
    ],
    "社会危害": [
        r"(?i)如何.{0,20}(盗取|窃取|入侵|破解|黑入).{0,10}(账号|系统|网站|服务器|密码)",
        r"(?i)(hack|crack|exploit|breach|infiltrate).{0,20}(system|account|server|network|website)",
        r"(?i)网络.{0,5}(诈骗|钓鱼|欺诈|攻击)",
        r"(?i)(phishing|scam|fraud|social engineering)",
    ],
}

DISCLAIMER_REQUIRED = [
    r"(?i)仅供参考",
    r"(?i)AI.{0,5}(生成|建议|输出|回答)",
    r"(?i)generated by AI",
    r"(?i)人工智能生成",
    r"(?i)disc?laimer",
    r"(?i)本内容",
]


def check_output(text: str, strict: bool = True) -> dict:
    """
    输出安全检测

    Args:
        text: 待检查文本
        strict: 严格模式（高危即拦截）/ 宽松模式（仅警告）

    Returns:
        {
            "passed": bool,
            "violations": [...],
            "has_disclaimer": bool,
            "warnings": [...]
        }
    """
    result = {
        "passed": True,
        "violations": [],
        "has_disclaimer": False,
        "warnings": [],
    }

    if not text or not text.strip():
        result["warnings"].append("输出为空")
        return result

    # 1. 敏感内容检测
    for category, patterns in SENSITIVE_PATTERNS.items():
        for pattern in patterns:
            matches = re.findall(pattern, text)
            if matches:
                violation = {
                    "category": category,
                    "pattern": pattern[:60],
                    "match": (matches[0] if isinstance(matches[0], str) else str(matches[0]))[:120],
                }
                result["violations"].append(violation)

    if result["violations"]:
        categories = set(v["category"] for v in result["violations"])
        if strict:
            result["passed"] = False

    # 2. 合规声明检测
    for pattern in DISCLAIMER_REQUIRED:
        if re.search(pattern, text):
            result["has_disclaimer"] = True
            break

    if not result["has_disclaimer"]:
        result["warnings"].append("缺少 AI 生成声明/免责声明")

    # 3. 输出长度预警
    char_count = len(text)
    if char_count < 10:
        result["warnings"].append("输出过短，可能无实际内容")
    elif char_count > 10000:
        result["warnings"].append("输出过长，建议分段")

    return result


def add_disclaimer(text: str, style: str = "standard") -> str:
    """自动添加合规声明"""
    disclaimers = {
        "standard": "\n\n⚠️ 本内容由 AI 生成，仅供参考。请结合实际情况判断。",
        "academic": "\n\n⚠️ 以上解答由 AI 辅助生成，建议理解推导过程后独立验证。",
        "medical": "\n\n⚠️ 本内容仅为信息参考，不构成医疗建议。请咨询专业医生。",
        "legal": "\n\n⚠️ 本内容不构成法律意见，具体情况请咨询专业律师。",
    }
    return text + disclaimers.get(style, disclaimers["standard"])


# ── CLI ────────────────────────────────────────────────────────────────


def main():
    import argparse
    parser = argparse.ArgumentParser(description="Skill-Sec 输出安全防护")
    parser.add_argument("--text", help="检查文本")
    parser.add_argument("--file", help="从文件读取")
    parser.add_argument("--add-disclaimer", choices=["standard", "academic", "medical", "legal"],
                        help="自动添加合规声明")
    parser.add_argument("--json", action="store_true", help="JSON 输出")

    args = parser.parse_args()

    text = None
    if args.text:
        text = args.text
    elif args.file:
        with open(args.file) as f:
            text = f.read()
    else:
        text = sys.stdin.read()

    if args.add_disclaimer:
        result = add_disclaimer(text, args.add_disclaimer)
        print(result)
        return 0

    if text:
        result = check_output(text)
        if args.json:
            print(json.dumps(result, ensure_ascii=False, indent=2))
        else:
            status = "✅ 通过" if result["passed"] else "❌ 拦截"
            print(f"\n  输出安全检查: {status}")
            if result["violations"]:
                for v in result["violations"]:
                    print(f"  🔴 [{v['category']}] {v['match'][:80]}")
            for w in result["warnings"]:
                print(f"  ⚠️  {w}")
            print(f"  合规声明: {'✅ 已标注' if result['has_disclaimer'] else '❌ 缺失'}")

    return 0 if result.get("passed", True) else 1


if __name__ == "__main__":
    main()
